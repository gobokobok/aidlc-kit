"""Marked blocks: the kit's part of a file the company also writes in.

Only the text between the markers is replaced, so a company's own content
in AGENTS.md, CODEOWNERS and the like is never touched.
"""

MD_MARKERS = ("<!-- aidlc:start (generated by `aidlc init`; changes inside this block are replaced) -->",
              "<!-- aidlc:end -->")
HASH_MARKERS = ("# aidlc:start (generated by aidlc; changes inside this block are replaced)",
                "# aidlc:end")


def upsert(existing: str | None, content: str, markers: tuple[str, str] = MD_MARKERS) -> str:
    """Insert or replace the block, leaving everything else untouched."""
    start_mark, end_mark = markers
    block = f"{start_mark}\n{content.strip()}\n{end_mark}\n"
    if not existing:
        return block
    start, end = existing.find(start_mark), existing.find(end_mark)
    if start != -1 and end > start:
        return existing[:start] + block + existing[end + len(end_mark):].lstrip("\n")
    return existing.rstrip("\n") + "\n\n" + block


def extract(existing: str | None, markers: tuple[str, str] = MD_MARKERS) -> str | None:
    """The block's content, or None if there is no block."""
    if not existing:
        return None
    start_mark, end_mark = markers
    start, end = existing.find(start_mark), existing.find(end_mark)
    if start == -1 or end < start:
        return None
    return existing[start + len(start_mark):end].strip()
